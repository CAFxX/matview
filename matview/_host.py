"""Static-typing contract shared by the compiler mixins.

``IncrementalViewCompiler`` is assembled from planner, maintenance, and dialect
mixins. Each mixin calls members that are implemented by the compiler class or
by a sibling mixin, which a type checker cannot see from the mixin alone.
``MixinHost`` declares exactly those cross-mixin members, with the signatures of
their real implementations, for the type checker only: the declarations live in
an ``if TYPE_CHECKING`` block, so at runtime ``MixinHost`` is an empty class and
the real implementations (which come earlier in the MRO) are the only ones that
exist.

``test_p1_mixin_host_contract.py`` verifies that every declaration here still
matches the live implementation (name, kind, and parameters), so the contract
cannot silently drift from the code it describes.
"""

